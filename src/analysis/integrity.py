"""T0: data integrity / leakage checks. Writes the 'Data integrity' section of reports/analysis.md.

python -m src.analysis.integrity
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

import numpy as np
import pandas as pd

from src.baselines import LABEL_NAMES, build_texts

MARKERS = {
    "OpenAI": r"openai", "Cohere": r"cohere", "Llama": r"llama", "Mistral": r"mistral",
    "MPT": r"\bmpt\b", "as an AI": r"as an ai\b", "Sure! Here": r"^\s*sure[!,.]? here",
    "special <|...|>": r"<\|[^|>]*\|>", "[INST]/<<SYS>>": r"\[/?INST\]|<<SYS>>",
    "</s> or <s>": r"</?s>", "leading whitespace": r"\A\s", "trailing whitespace": r"\s\Z",
    "trailing newline": r"\n\Z", "starts with newline": r"\A\n", "contains blank line": r"\n\n",
    "contains CR": r"\r",
}


def normalise(text: str) -> str:
    """Lowercase, drop non-alphanumerics, collapse whitespace (used for exact-dup hashing)."""
    t = re.sub(r"[^0-9a-z]+", " ", str(text).lower())
    return " ".join(t.split())


def text_hash(text: str) -> str:
    return hashlib.md5(normalise(text).encode("utf-8")).hexdigest()


def split_overlaps(df: pd.DataFrame, col: str, key: str = "source_id") -> dict:
    sets = {s: set(g[key]) for s, g in df.groupby(col)}
    names = sorted(sets)
    return {f"{a}/{b}": len(sets[a] & sets[b]) for i, a in enumerate(names) for b in names[i + 1:]}


def cross_split_dups(df: pd.DataFrame, col: str, text_col: str = "generation") -> pd.DataFrame:
    """Rows whose normalised-text hash appears in >1 split. Returns those rows (with 'h')."""
    h = df[text_col].map(text_hash)
    nsplit = df.assign(h=h).groupby("h")[col].nunique()
    bad = nsplit[nsplit > 1].index
    return df.assign(h=h)[h.isin(bad)]


def marker_table(df: pd.DataFrame) -> pd.DataFrame:
    rows = {}
    for name, pat in MARKERS.items():
        flags = re.M if name == "Sure! Here" else 0
        rx = re.compile(pat, re.I | flags)
        rows[name] = df.groupby("model")["generation"].apply(
            lambda s: int(sum(bool(rx.search(x)) for x in s.fillna(""))))
    return pd.DataFrame(rows).T[list(LABEL_NAMES)]


def near_dups_test_vs_train(df, thr=0.9):
    from sklearn.feature_extraction.text import TfidfVectorizer
    tr, te = df[df.split == "train"], df[df.split == "test"]
    v = TfidfVectorizer(sublinear_tf=True, min_df=2, dtype=np.float32)
    A = v.fit_transform(tr.generation.fillna(""))
    B = v.transform(te.generation.fillna(""))
    mx = np.zeros(B.shape[0], dtype=np.float32)
    for i in range(0, B.shape[0], 400):
        mx[i:i + 400] = (B[i:i + 400] @ A.T).max(axis=1).toarray().ravel()
    return int((mx >= thr).sum()), float(np.median(mx)), float(mx.max()), int(len(mx))


def newline_stats(df):
    tr = df[df.split == "train"]
    frac = tr.groupby("model")["generation"].apply(
        lambda s: float(np.mean([("\n" in x) for x in s.fillna("")]))).reindex(LABEL_NAMES)
    mean = tr.groupby("model")["generation"].apply(
        lambda s: float(np.mean([x.count("\n") for x in s.fillna("")]))).reindex(LABEL_NAMES)
    return frac, mean


def replace_section(text: str, header: str, body: str) -> str:
    """Replace the '## ...' section starting with `header` (up to next '## ' or EOF), else append."""
    i = text.find(header)
    if i < 0:
        return text.rstrip("\n") + "\n\n" + body.rstrip("\n") + "\n"
    j = text.find("\n## ", i + len(header))
    tail = text[j + 1:] if j >= 0 else ""
    return text[:i] + body.rstrip("\n") + "\n" + ("\n" + tail if tail else "")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--main", default="data/processed/raid_main.parquet")
    ap.add_argument("--rq3", default="data/processed/raid_rq3.parquet")
    ap.add_argument("--out", default="reports/analysis.md")
    a = ap.parse_args(argv)
    df = pd.read_parquet(a.main)
    d3 = pd.read_parquet(a.rq3)
    d3 = d3.assign(sp=d3["split_rq3"].replace({"test_indomain": "test"}))
    ov = split_overlaps(d3, "sp")
    dups = cross_split_dups(d3, "sp")
    pair = dups.groupby("h")["sp"].apply(lambda s: "/".join(sorted(set(s))))
    pair_counts = pair.value_counts().to_dict()
    nd = near_dups_test_vs_train(df)
    mt = marker_table(df)
    nl_frac, nl_mean = newline_stats(df)
    sample = df[df.generation.str.contains("\n")].head(200)
    nl_in_tfidf = sum("<NL>" in t.split() for t in build_texts(sample, "output"))

    L = ["## Data integrity (T0)", "",
         "Generated by `python -m src.analysis.integrity`. Splits: train/val/test from `raid_main`; test_code from `raid_rq3`.", "",
         "### 1. source_id overlap across splits", "",
         "| pair | shared source_ids |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in ov.items()]
    L += ["", f"Result: {'PASS, all zero' if all(v == 0 for v in ov.values()) else 'FAIL'}.", "",
          "### 2. Duplicate generations across splits", "",
          "- Exact duplicates (normalised: lowercase, alphanumerics only, whitespace collapsed; MD5) of a generation text appearing in more than one split "
          f"(train/val/test/test_code): {len(pair)} distinct texts / {len(dups)} rows. Split pairs: {pair_counts or 'none'}.",
          f"- Near-duplicates (word TF-IDF cosine >= 0.9 between a TEST generation and its nearest TRAIN generation, vectorizer fit on train): "
          f"{nd[0]} of {nd[3]} test rows; median nearest-train cosine {nd[1]:.3f}, max {nd[2]:.3f}. (Cosine used in place of MinHash; cheap at this size.)", "",
          "### 3. Fit-on-train-only audit (code inspection)", "",
          "- TF-IDF vectorizer: `src/baselines.py` line 199 `Xtr = vec.fit_transform(build_texts(tr, ...))  # TRAIN only`; val/test only `vec.transform` (lines 200, 228-229).",
          "- C selection: `src/baselines.py` lines 206-211: LR fit per C on train, `curve[C]` computed on `Xva`/`yva` (VAL macro-F1), `best_i = argmax`. Test is evaluated only afterwards (lines 222-229) and never feeds back.",
          "- Neural vocab: `src/preprocess.py` `build_vocab_from_df` (lines 442-453) asserts `split == 'train'`; `src/train.py` line 86 `build_vocab_from_df(splits['train'], ...)`. Val/test OOV tokens map to `<UNK>`.",
          "- Neural early stopping / checkpoint selection uses VAL; test predictions are recorded at the best-val checkpoint.",
          "- Note: the C grid was extended to include 1000 because best C=100 sat on the old edge (comment at `C_GRID`, line 110); that decision is val-driven.", "",
          "### 4. Model-identifying strings in generations (text splits, all 16,000 rows; number of generations matching, 3,200 per model)", "",
          "| pattern | " + " | ".join(LABEL_NAMES) + " |", "|---|" + "---|" * 5]
    for name, r in mt.iterrows():
        L.append(f"| {name} | " + " | ".join(str(int(x)) for x in r) + " |")
    L += ["", "### 5. Newline handling: TF-IDF vs neural tokenizer", "",
          "TRAIN generations: fraction containing a newline and mean newline count:", "",
          "| model | frac with newline | mean newline count |", "|---|---|---|"]
    L += [f"| {m} | {nl_frac[m]:.3f} | {nl_mean[m]:.2f} |" for m in LABEL_NAMES]
    L += ["", "Finding: the suspected mismatch does NOT occur. `baselines.build_texts` calls `src.preprocess.tokenize` first, "
          "which maps newline / CRLF to the literal token `<NL>` and joins tokens with single spaces; `str.split` then splits only on those spaces, "
          f"so `<NL>` is a TF-IDF feature exactly as in the neural path (checked on {len(sample)} newline-containing generations: "
          f"{nl_in_tfidf} contain `<NL>` in the TF-IDF input). Both paths see the same token stream (same 64/256 truncation, case kept). "
          "Remaining differences: TF-IDF uses word 1-2grams, min_df=2, 200k features; the neural vocab is unigram, min_freq=2, 30k cap. "
          "In the +char variant, `char_wb` 2-5grams run over the space-joined token string, so `<NL>` appears as the characters `<NL>`.", ""]
    out = Path(a.out)
    out.parent.mkdir(exist_ok=True)
    old = out.read_text(encoding="utf-8") if out.exists() else "# Analysis\n\n"
    out.write_text(replace_section(old, "## Data integrity (T0)", "\n".join(L)), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
