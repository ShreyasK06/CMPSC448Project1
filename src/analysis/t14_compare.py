"""Best-vs-best comparison of the neural models with TF-IDF+LR on the same TEST rows.

python -m src.analysis.t14_compare  -> section '## Neural vs TF-IDF at each model's best input length' in reports/{analysis,results}.md

TF-IDF rows: K256 (same 256-token output cap as the original neural runs) and Kfull (no truncation), from
runs/tfidf_ablations_test_pred.npz (hard predictions, C chosen on VAL). Neural rows: seed ensembles (mean class probability) of the
runs listed in NEURAL, all variant `output`. Exact McNemar on identical test rows; Holm over every test in the table; cluster
bootstrap CIs over test source_ids.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from src.analysis.common import ci_row, fmt_ci, md_table, write_section
from src.analysis.stats import holm, load_preds, mcnemar_exact
from src.analysis.t8_report import ensemble, load_group

HEADER = "## Neural vs TF-IDF at each model's best input length"
# label, model, tag (variant output)
NEURAL = [("CNN base, cap 256", "cnn", "base"), ("CNN ext, cap 512", "cnn", "ext_len512"),
          ("CNN ext, cap 2048", "cnn", "ext_len2048"),
          ("BiLSTM base, cap 256", "bilstm", "base"), ("BiLSTM ext, cap 512", "bilstm", "ext_len512"),
          ("BiLSTM ext, cap 2048", "bilstm", "ext_len2048")]
TFIDF = [("TF-IDF K256 (256-token output cap)", "K256"), ("TF-IDF Kfull (no truncation)", "Kfull")]


def _row(label, kind, n, e):
    a, f, ac, fc = ci_row(e["y"], e["pred"], e["sid"], n_boot=2000)
    return [label, kind, n, fmt_ci(a, ac), fmt_ci(f, fc)]


def build(runs="runs"):
    ref = load_preds(Path(runs) / "tfidf_output_base.npz")
    y, sid = ref["y"], ref["sid"]
    tf = np.load(Path(runs) / "tfidf_ablations_test_pred.npz")
    ents = []  # (label, kind, n_seeds, dict(y,sid,pred))
    for lab, key in TFIDF:
        ents.append((lab, "TF-IDF+LR (1 fit)", 1, dict(y=y, sid=sid, pred=tf[key].astype(int))))
    for lab, model, tag in NEURAL:
        g = load_group(runs, model, "output", tag)
        if len(g) < 3:
            continue
        e = ensemble(g)
        if not (np.array_equal(e["sid"], sid) and np.array_equal(e["y"], y)):
            raise ValueError(f"{lab}: test rows not aligned with the TF-IDF predictions")
        ents.append((lab, f"neural, {len(g)}-seed ensemble", len(g), e))
    rows = [_row(l, k, n, e) for l, k, n, e in ents]
    # tests: every neural entry vs every TF-IDF entry
    tests = []
    for tl, _, _, te in ents[:len(TFIDF)]:
        for nl, _, _, ne in ents[len(TFIDF):]:
            p, t_only, n_only = mcnemar_exact(te["pred"] == y, ne["pred"] == y)
            tests.append((tl, nl, t_only, n_only, p))
    adj, rej = holm([t[4] for t in tests]) if tests else ([], [])
    mc = [[t[0], t[1], t[2], t[3], f"{t[4]:.3g}", f"{a:.3g}", "yes" if r else "no"] for t, a, r in zip(tests, adj, rej)]
    return rows, mc


def body(rows, mc):
    L = [HEADER, "",
         "Generated by `python -m src.analysis.t14_compare`. Variant `output`, [TEST split: test], same 2,400 rows for every model. "
         "TF-IDF is one deterministic fit per setting with C chosen on [VAL split] macro-F1 (`K256` = the original 256-token cap, "
         "`Kfull` = no truncation; from the T6 ablation). Neural rows are mean-probability seed ensembles; `ext` = T9 config, "
         "selected on VAL only. CIs: cluster bootstrap over the 480 test source_ids (2,000 resamples). McNemar: exact, TF-IDF-only "
         "vs neural-only correct, Holm over all tests below. Rows within a source_id are not independent, so p-values are "
         "somewhat optimistic. Single-split numbers: the ensemble accuracies are also optimistic relative to a single model.", ""]
    L += md_table(["model", "kind", "n fits", "TEST acc % [95% CI]", "TEST macro-F1 % [95% CI]"], rows)
    L += ["", "McNemar, TF-IDF vs neural (A = TF-IDF):", ""]
    L += md_table(["TF-IDF run (A)", "neural run (B)", "A-only correct", "B-only correct", "exact p", "Holm p", "reject @0.05"], mc)
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--analysis", default="reports/analysis.md")
    ap.add_argument("--results", default="reports/results.md")
    a = ap.parse_args(argv)
    b = body(*build(a.runs))
    write_section(HEADER, b, analysis_md=a.analysis, results_md=a.results, results_body=b)
    print(b)


if __name__ == "__main__":
    main()
