"""Phase 3-4 report: output-length cap x tuned config, and the winning config (ext, cap 512) on both variants.

python -m src.analysis.t13_report   -> section '## Output length and tuned config (phase 3-4)' in reports/{analysis,results}.md

All comparisons use seeds 0-2 for every row (seed-matched 3-seed ensembles); the 5-seed rows are shown separately.
Reference for each (model, variant) is the stage-1 'base' config at the default 256-token cap.
"""
from __future__ import annotations

import argparse

from src.analysis.common import md_table, write_section
from src.analysis.t8_report import PM, _ci_cells, _cmp_cells, _fill_mcnemar, _weights, ensemble, load_group, summarise

HEADER = "## Output length and tuned config (phase 3-4)"
# variant -> [(label, tag)], first entry is the reference
RUNS = {
    "output": [("base, cap 256 (reference)", "base"), ("base, cap 512", "abl_len512"), ("base, cap 1024", "abl_len1024"),
               ("base, cap 2048", "abl_len2048"), ("ext, cap 256", "ext"), ("ext, cap 512", "ext_len512"),
               ("ext, cap 1024", "ext_len1024"), ("ext, cap 2048", "ext_len2048")],
    "both": [("base, cap 256 (reference)", "base"), ("ext, cap 256", "ext"), ("ext, cap 512", "ext_len512")],
}
HEAD = ["model", "variant", "run", "n seeds", "[VAL split] acc / macro-F1 %", "[TEST split: test] acc / macro-F1 %",
        "3-seed ensemble TEST acc % [95% CI]", "ensemble TEST macro-F1 % [95% CI]",
        "Δ ensemble TEST acc vs reference, pp [95% paired CI]", "McNemar vs reference (ref-only/run-only correct; exact p; Holm)"]


def build(runs="runs"):
    rows = []
    for model in ("cnn", "bilstm"):
        for variant, spec in RUNS.items():
            groups = [(lab, tag, load_group(runs, model, variant, tag)) for lab, tag in spec]
            groups = [g for g in groups if g[2]]
            if not groups or groups[0][1] != "base":
                continue
            m3 = {tag: [x for x in g if x["seed"] < 3] for _, tag, g in groups}
            ens = {tag: ensemble(m3[tag]) if len(m3[tag]) == 3 else None for _, tag, _ in groups}
            W = _weights(list(ens.values()))
            ref = ens["base"]
            block = []
            for lab, tag, g in groups:
                s = summarise(g)
                ci = _ci_cells(ens[tag])
                diff, mc = ("(reference)", None) if tag == "base" else _cmp_cells(ens[tag], ref, W)
                block.append([model, variant, lab, s["n"], s["val"], s["test"], ci[0], ci[1], diff, mc])
            g5 = load_group(runs, model, variant, "ext_len512")
            if len(g5) > 3:
                e5 = ensemble(g5)
                s = summarise(g5)
                ci = _ci_cells(e5)
                diff, mc = _cmp_cells(e5, ref, W)
                block.append([model, variant, "ext, cap 512, all seeds (5-seed ensemble)", s["n"], s["val"], s["test"],
                              ci[0], ci[1], diff, mc])
            _fill_mcnemar(block, 9)
            rows += block
    return rows


def body(rows):
    L = [HEADER, "",
         "Generated by `python -m src.analysis.t13_report`. Variants `output` and `both`; every row is trained on the TRAIN split, "
         "early-stopped on [VAL split], and evaluated once on [TEST split: test] at the best-VAL checkpoint. The cap is the output-token "
         "cap (prompt cap stays 64); `base` = stage-1 tuned config, `ext` = T9 extended-tuning config "
         "(`reports/tuning/*_output_ext.json`), both selected on VAL only. The best setting (ext, cap 512) was chosen on mean VAL "
         "macro-F1 from the `output` runs before the `both` runs and seeds 3-4 existed. Columns are mean " + PM + " sample std "
         "over ALL seeds listed in the n-seeds column (the per-seed columns therefore include seeds 3-4 where n=5). The ensemble, CI and paired-difference columns use seeds 0-2 for every row so rows are comparable; the last "
         "row of a block adds seeds 3-4 (5-seed ensemble, compared with the 3-seed reference). CIs: cluster bootstrap over the 480 "
         "test source_ids (2,000 resamples, shared, paired for the difference). Rows within a source_id are not independent, so "
         "McNemar p-values are somewhat optimistic. These are single-split numbers: no cross-validated number exists for the neural "
         "models (TF-IDF grouped CV is in its own section above), and the [VAL split] column is selection data, not a "
         "generalization estimate.", ""]
    L += md_table(HEAD, rows)
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--analysis", default="reports/analysis.md")
    ap.add_argument("--results", default="reports/results.md")
    a = ap.parse_args(argv)
    b = body(build(a.runs))
    write_section(HEADER, b, analysis_md=a.analysis, results_md=a.results, results_body=b)
    print(b)


if __name__ == "__main__":
    main()
